#!/usr/bin/env node
/**
 * Close-out logger for a marketing run. Consumes the outputs of every prior step
 * and does the bookkeeping:
 *
 *   1. Write docs/listings/<slug>.md  -- per-listing detail file with full
 *      launch summary, Buffer post IDs, Mailjet draft IDs, media URLs. Acts as
 *      the listing's home doc until the next CMA/MLS pull enriches it.
 *   2. Bump data/marketing/counter.json    -- increments rotation counter so the
 *      next run renders the next A/B/C variant.
 *   3. (Best-effort) Lofty note            -- POSTs a short launch-summary note
 *      to the seller lead if a lead_id is known. Either pass --lead-id <id>
 *      on the CLI or put "lofty_lead_id": N in inputs.json.
 *   4. Write <run-dir>/launch-log.json     -- machine-readable summary so later
 *      steps / audits can see what happened.
 *
 * active-listings.md is NOT touched here -- it is auto-regenerated by
 * scripts/refresh-active-listings.js from the weekly listing-reports pull.
 * The launch stage happens days before the first weekly pull sees the new
 * listing, so the delay is fine.
 *
 * Usage:
 *   node log-marketing-launch.js <run-dir>
 *   node log-marketing-launch.js <run-dir> --lead-id 12345
 *   node log-marketing-launch.js <run-dir> --no-lofty          # skip Lofty note
 *   node log-marketing-launch.js <run-dir> --dry-run           # render files without writing
 *
 * Reads:
 *   <run-dir>/inputs.json           -- listing inputs
 *   <run-dir>/posts.json            -- posts + emails skeleton + filled copy
 *   <run-dir>/buffer-updates.json   -- Buffer step 4 output (optional)
 *   <run-dir>/mailjet-drafts.json   -- Mailjet step 5 output (optional)
 *
 * Writes:
 *   docs/listings/<slug>.md
 *   data/marketing/counter.json
 *   <run-dir>/launch-log.json
 */
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const REPO_ROOT = path.resolve(__dirname, '..', '..', '..', '..');
const LISTINGS_DIR = path.join(REPO_ROOT, 'knowledge', 'listings');
const COUNTER_PATH = path.join(REPO_ROOT, 'data', 'marketing', 'counter.json');

function die(msg) { console.error(msg); process.exit(1); }
function readJson(p) { return JSON.parse(fs.readFileSync(p, 'utf8')); }
function writeJson(p, obj) { fs.writeFileSync(p, JSON.stringify(obj, null, 2)); }

function slugify(address) {
  // "1234 Example Road, Springfield, BC" -> "1234-example-road"
  const streetPart = address.split(',')[0].trim();
  return streetPart.toLowerCase()
    .replace(/[^\w\s]/g, '')
    .replace(/\s+/g, '-');
}

// Rotation set 2026-04-21: D and E only. Must match the ROTATION
// constant in render-all.js -- if one changes, change both.
function variantFromCounter(n) {
  return ['D', 'E'][n % 2];
}

function tableRow(cells) {
  return '| ' + cells.map(c => String(c ?? '').replace(/\|/g, '\\|')).join(' | ') + ' |';
}

function bufferResultsByStage(bufferUpdates) {
  const out = {};
  if (!bufferUpdates || !Array.isArray(bufferUpdates.results)) return out;
  for (const r of bufferUpdates.results) {
    if (!r.id) continue;
    out[r.id] = r;
  }
  return out;
}

function findChannel(channels, service) {
  return (channels || []).find(c => c.service === service);
}

function buildDetailMarkdown({ inputs, posts, bufferUpdates, mailjetDrafts, counter }) {
  const variant = variantFromCounter(counter);
  const byStage = bufferResultsByStage(bufferUpdates);
  const mjDraftsById = {};
  for (const d of (mailjetDrafts?.drafts || [])) mjDraftsById[d.id] = d;

  const lines = [];
  lines.push(`# ${inputs.address}`);
  lines.push('');
  lines.push('_Detail file seeded by marketing launch. Weekly listing pulls enrich this with MLS room dimensions, description, photos, etc._');
  lines.push('');
  lines.push('## Launch Summary');
  lines.push(`- **Go-Live**: ${inputs.go_live_date || 'n/a'}`);
  lines.push(`- **Open House**: ${inputs.open_house_display || 'n/a'}`);
  lines.push(`- **Marketing run**: \`${posts.run_id}\` (variant ${variant}, counter ${counter})`);
  lines.push(`- **Status**: Active`);
  lines.push('');
  lines.push('## Quick Facts');
  lines.push(`- **Price**: ${inputs.price || 'TBD'}`);
  lines.push(`- **Features**: ${inputs.features_line || ''}`);
  if (inputs.unique_features) lines.push(`- **Unique**: ${inputs.unique_features}`);
  if (inputs.recreational_feature) lines.push(`- **Recreational**: ${inputs.recreational_feature}`);
  lines.push('');

  // Social posts table
  lines.push('## Social Posts (Buffer)');
  lines.push('');
  lines.push(tableRow(['Stage', 'Scheduled', 'IG ID', 'FB ID', 'Status']));
  lines.push(tableRow(['---', '---', '---', '---', '---']));
  for (const p of (posts.posts || [])) {
    const r = byStage[p.id];
    const channels = r?.channels || [];
    const ig = findChannel(channels, 'instagram');
    const fb = findChannel(channels, 'facebook');
    lines.push(tableRow([
      p.id,
      p.scheduled_at_iso || '',
      ig ? (ig.post_id || ig.status) : '-',
      fb ? (fb.post_id || fb.status) : '-',
      r ? r.status : 'not-run',
    ]));
  }
  lines.push('');

  // Email blasts table
  lines.push('## Email Blasts (Mailjet)');
  lines.push('');
  lines.push(tableRow(['Stage', 'Scheduled', 'Draft ID', 'Subject', 'Status']));
  lines.push(tableRow(['---', '---', '---', '---', '---']));
  for (const e of (posts.emails || [])) {
    const d = mjDraftsById[e.id];
    lines.push(tableRow([
      e.id,
      e.scheduled_at_iso || '',
      d ? d.draft_id : '-',
      (e.subject || '').slice(0, 60),
      d ? d.status : 'not-run',
    ]));
  }
  lines.push('');

  // Media
  lines.push('## Media');
  if (bufferUpdates?.results) {
    const seenDrive = new Set();
    for (const r of bufferUpdates.results) {
      if (!r.media) continue;
      if (seenDrive.has(r.media.drive_file_id)) continue;
      seenDrive.add(r.media.drive_file_id);
      const label = r.id.replace(/-/g, ' ');
      lines.push(`- **${label} graphic**: ${r.media.web_view_link || r.media.drive_url}`);
    }
  }
  if (inputs.area_photo?.drive_id) {
    lines.push(`- **Area photo**: https://drive.google.com/open?id=${inputs.area_photo.drive_id}`);
  }
  if (inputs.recreational_photo?.drive_id) {
    lines.push(`- **Recreational photo**: https://drive.google.com/open?id=${inputs.recreational_photo.drive_id}`);
  }
  lines.push('');
  lines.push(`## Run Directory`);
  lines.push(`\`data/marketing/runs/${posts.run_id}/\``);
  lines.push('');

  return lines.join('\n') + '\n';
}

async function postLoftyNote(leadId, content) {
  // Env var first; fall back to the host repo's .env. Lofty is best-effort, so
  // a missing key is a skip, not a thrown ENOENT that kills the log step.
  let token = process.env.LOFTY_API_KEY;
  if (!token) {
    const envPath = path.join(REPO_ROOT, '.env');
    if (!fs.existsSync(envPath)) return { ok: false, error: 'LOFTY_API_KEY not set and no .env found' };
    const m = fs.readFileSync(envPath, 'utf8').match(/^LOFTY_API_KEY=(.+)$/m);
    if (!m) return { ok: false, error: 'LOFTY_API_KEY missing in .env' };
    token = m[1].trim();
  }
  const res = await fetch('https://api.chime.me/v1.0/notes', {
    method: 'POST',
    headers: { 'Authorization': `token ${token}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ leadId: Number(leadId), content }),
  });
  const text = await res.text();
  return { ok: res.ok, status: res.status, body: text };
}

async function main() {
  const args = process.argv.slice(2);
  const runDir = path.resolve(args.find(a => !a.startsWith('--')) || '.');
  const dryRun = args.includes('--dry-run');
  const noLofty = args.includes('--no-lofty');
  const leadIdx = args.indexOf('--lead-id');
  const cliLeadId = leadIdx >= 0 ? args[leadIdx + 1] : null;

  const postsPath   = path.join(runDir, 'posts.json');
  const inputsPath  = path.join(runDir, 'inputs.json');
  if (!fs.existsSync(postsPath))  die(`posts.json not found at ${postsPath}`);
  if (!fs.existsSync(inputsPath)) die(`inputs.json not found at ${inputsPath}`);

  const posts  = readJson(postsPath);
  const inputs = readJson(inputsPath);
  const bufferUpdates = fs.existsSync(path.join(runDir, 'buffer-updates.json'))
    ? readJson(path.join(runDir, 'buffer-updates.json')) : null;
  const mailjetDrafts = fs.existsSync(path.join(runDir, 'mailjet-drafts.json'))
    ? readJson(path.join(runDir, 'mailjet-drafts.json')) : null;

  // Load + increment counter (we'll write it back only on --dry-run=false)
  let counterData;
  if (fs.existsSync(COUNTER_PATH)) {
    counterData = readJson(COUNTER_PATH);
  } else {
    counterData = { counter: 0, last_run: null, last_address: null };
  }
  const counterBefore = counterData.counter;

  // Build detail markdown using the CURRENT counter (what this run used)
  const detailMd = buildDetailMarkdown({
    inputs, posts, bufferUpdates, mailjetDrafts, counter: counterBefore,
  });

  const slug = slugify(inputs.address);
  // Always write launch summary to <slug>-launch.md so it never clobbers an
  // MLS-enriched <slug>.md that may already exist (maintained by the weekly
  // listing-reports pull + manual edits). Master detail file is a separate
  // artifact with different lifecycle.
  const detailPath = path.join(LISTINGS_DIR, `${slug}-launch.md`);

  if (!dryRun) {
    fs.mkdirSync(LISTINGS_DIR, { recursive: true });
    fs.writeFileSync(detailPath, detailMd);
    console.log(`wrote ${path.relative(REPO_ROOT, detailPath)}`);
  } else {
    console.log(`[dry-run] would write ${path.relative(REPO_ROOT, detailPath)} (${detailMd.length} bytes)`);
  }

  // Lofty note
  const leadId = cliLeadId || inputs.lofty_lead_id || null;
  let loftyResult = { attempted: false };
  if (!noLofty && leadId) {
    const scheduledCount = (bufferUpdates?.scheduled_count || 0) + (mailjetDrafts?.scheduled_count || 0);
    const content = [
      `[${new Date().toISOString().slice(0, 10)}] Marketing launched: ${inputs.address}.`,
      `${scheduledCount} items scheduled (Buffer posts + Mailjet emails).`,
      `Open house ${inputs.open_house_display || 'TBD'}.`,
      `Run: ${posts.run_id}.`,
    ].join(' ');
    if (!dryRun) {
      try {
        const r = await postLoftyNote(leadId, content);
        loftyResult = { attempted: true, lead_id: leadId, ok: r.ok, status: r.status };
        console.log(`lofty note: ${r.ok ? 'ok' : 'failed'} (lead ${leadId}, HTTP ${r.status})`);
      } catch (e) {
        loftyResult = { attempted: true, lead_id: leadId, ok: false, error: e.message };
        console.error(`lofty note failed: ${e.message}`);
      }
    } else {
      loftyResult = { attempted: true, lead_id: leadId, dry_run: true, content };
      console.log(`[dry-run] would POST lofty note to lead ${leadId}: ${content.slice(0, 80)}...`);
    }
  } else if (!noLofty) {
    console.log(`lofty note: SKIPPED (no lead_id provided, pass --lead-id or set lofty_lead_id in inputs.json)`);
    loftyResult = { attempted: false, reason: 'no-lead-id' };
  } else {
    console.log(`lofty note: SKIPPED (--no-lofty flag)`);
    loftyResult = { attempted: false, reason: 'no-lofty-flag' };
  }

  // Bump counter
  const nextCounter = counterBefore + 1;
  counterData.counter = nextCounter;
  counterData.last_run = posts.run_id;
  counterData.last_address = inputs.address;
  counterData.last_run_at = new Date().toISOString();
  if (!dryRun) {
    fs.mkdirSync(path.dirname(COUNTER_PATH), { recursive: true });
    writeJson(COUNTER_PATH, counterData);
    console.log(`counter: ${counterBefore} -> ${nextCounter} (next variant: ${variantFromCounter(nextCounter)})`);
  } else {
    console.log(`[dry-run] would bump counter: ${counterBefore} -> ${nextCounter}`);
  }

  // Launch log
  const launchLog = {
    run_id: posts.run_id,
    address: inputs.address,
    go_live: inputs.go_live_date,
    counter_before: counterBefore,
    counter_after: nextCounter,
    variant: variantFromCounter(counterBefore),
    detail_file: path.relative(REPO_ROOT, detailPath),
    buffer_scheduled: bufferUpdates?.scheduled_count || 0,
    buffer_failed: bufferUpdates?.failed_count || 0,
    mailjet_scheduled: mailjetDrafts?.scheduled_count || 0,
    mailjet_drafted: mailjetDrafts?.draft_count || 0,
    mailjet_failed: mailjetDrafts?.failed_count || 0,
    lofty: loftyResult,
    logged_at: new Date().toISOString(),
    dry_run: dryRun,
  };
  const logPath = path.join(runDir, 'launch-log.json');
  if (!dryRun) {
    writeJson(logPath, launchLog);
    console.log(`wrote ${path.relative(REPO_ROOT, logPath)}`);
  }
  console.log(`\nlaunch complete: variant ${launchLog.variant}, ` +
    `${launchLog.buffer_scheduled} social + ${launchLog.mailjet_scheduled + launchLog.mailjet_drafted} email items, ` +
    `counter @ ${launchLog.counter_after}`);
}

main().catch((e) => { console.error(e); process.exit(1); });
